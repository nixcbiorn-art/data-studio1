"""python test_name_normalizer.py — самопроверка нормализатора."""
from redcat.sources import name_normalizer as nn

N = nn.normalize
# (вход, ожидаемый normalize)
CASES = [
    ("ЖК «Скай Гарден», корпус 3", "скай гарден"),
    ("Жилой комплекс Sky  Garden (Москва)", "sky garden"),
    ("ЖК \"Амбер Сити\" 2-я очередь", "амбер сити"),
    ("Амбер Сити, II очередь", "амбер сити"),
    ("Амбер Сити к.2 стр. 1", "амбер сити"),
    ("1-й Измайловский", "1 измайловский"),
    ("Первый Измайловский", "1 измайловский"),
    ("Третья Гражданская", "3 гражданская"),
    ("ЖК&nbsp;Лайм", "лайм"),
    ("&quot;Скай&quot; ЖК", "скай"),
    ("Ёлки Парк", "елки парк"),
    ("Сkай Гарден", "скай гарден"),            # латинская k
    ("Sкy Garden", "sky garden"),              # кириллическая к
    ("Дом на Мосфильмовской", "дом на мосфильмовской"),   # «дом» не режем
    ("Квартал Триумфальный", "квартал триумфальный"),
    ("MIX Tower", "mix tower"),                # MIX — не римское число
    ("Скай Гарден-2", "скай гарден 2"),
    ("(Sky Garden)", "sky garden"),
    ("Level Селигерская", "level селигерская"),
    ("The Residences", "residences"),
    ("дом «Обручева 30»", "обручева 30"),
    ("Клубный дом «The Lake»", "lake"),
    ("Архитектор(Москва)", "архитектор"),
    ("ЖК «ЛУЧИ»", "лучи"),
    ("", None), (None, None), ("Корпус 3", None), ("ЖК", None),
]
bad = 0
for raw, exp in CASES:
    got = N(raw)
    if got != exp:
        bad += 1
        print(f"✗ {raw!r}: {got!r} (ждали {exp!r})")

# пары, которые ДОЛЖНЫ считаться одним ЖК (score >= 0.9)
SAME = [("Скай Гарден", "Sky Garden"), ("Амбер Сити", "Amber City"),
        ("Сидней Прайм", "Sydney Prime"), ("Сидней Сити", "Sydney City"),
        ("Роттердам", "Rotterdam"), ("Эко Бунино", "ЭкоБунино"),
        ("Ново-Переделкино", "Новопеределкино"),
        ("ЖК Скай Гарден к.3", "Sky Garden"),
        ("ЖК «ВЕЙВ»", "Wave"), ("Лэйк", "Клубный дом «The Lake»"),
        ("ЖК «ЗИЛАРТ»", "ЗилАрт"), ("дом «Обручева 30»", "Обручева 30"),
        ("Архитектор", "Архитектор(Москва)"),
        ("ЖК «Дмитровское небо»", "Дмитровское Небо")]
for a, b in SAME:
    s, why = nn.similarity(a, b)
    if s < 0.9:
        bad += 1
        print(f"✗ должны совпасть: {a!r} ~ {b!r}: {s:.2f} {why}")

# пары, которые НЕ должны сливаться автоматически
DIFF = [("Скай Гарден 1", "Скай Гарден 2"), ("Сити Парк", "Сата Парк"),
        ("Лайм", "Лом"), ("Архитектор", "Стратег"), ("Первый Дубровский", "Второй Дубровский")]
for a, b in DIFF:
    s, why = nn.similarity(a, b)
    if s >= 0.9:
        bad += 1
        print(f"✗ не должны сливаться: {a!r} ~ {b!r}: {s:.2f} {why}")

# автосопоставление списков
res = nn.auto_aliases(
    ["Скай Гарден", "Амбер Сити", "Сидней Прайм", "Эко Бунино", "Лайм", "Общий"],
    ["Sky Garden", "Amber City", "Sydney Prime", "ЭкоБунино", "Лом", "Общий"])
exp = {"скай гарден": "sky garden", "амбер сити": "amber city",
       "сидней прайм": "sydney prime", "эко бунино": "экобунино"}
if res["aliases"] != exp:
    bad += 1
    print("✗ auto_aliases:", res)

# данные со скриншотов: с опорой на счётчики строк
left = {"ЖК «ВЕЙВ»": 292, "ЖК «Дмитровское небо»": 48, "ЖК «ЗИЛАРТ»": 793,
        "ЖК «ЛУЧИ»": 493, "дом «Обручева 30»": 336, "Хольм": 570,
        "Архитектор": 30, "Лэйк": 3, "Римский": 4, "Движение. Говорово": 1}
right = {"Wave": 284, "ZILART GRAND": 62, "ZILART SPARK": 420, "Дмитровское Небо": 47,
         "ЗилАрт": 724, "Лучи": 447, "Марк": 242, "Обручева 30": 337, "Хольм.Эйк": 571,
         "Архитектор(Москва)": 29, "Дубровицы клаб": 73,
         "Клубный дом «The Lake»": 3, "Мартемьяново Клаб": 34}
ln = {nn.normalize(k): v for k, v in left.items()}
rn = {nn.normalize(k): v for k, v in right.items()}
r = nn.auto_aliases(list(left), list(right), left_counts=ln, right_counts=rn)
matched = set(r["aliases"]) | (set(ln) & set(rn))
for name in ("вейв", "хольм", "лэйк", "зиларт", "лучи", "обручева 30",
             "дмитровское небо", "архитектор"):
    if name not in matched:
        bad += 1
        print("✗ не сопоставлено:", name, r["aliases"])
for wrong in ("римский", "движение говорово"):     # у них нет пары справа
    if wrong in r["aliases"]:
        bad += 1
        print("✗ ложная пара:", wrong, "→", r["aliases"][wrong])
print("авто-пары:", r["aliases"])

# неоднозначность: два левых претендуют на один правый → не склеивать
amb = nn.auto_aliases(["Сити Парк А", "Сити Парк Б"], ["City Park"])
if amb["aliases"]:
    bad += 1
    print("✗ неоднозначное склеено:", amb)

# цепочки алиасов и циклы
assert nn.canon("A", {"a": "b", "b": "c"}) == "c"
assert nn.canon("A", {"a": "b", "b": "a"}) in ("a", "b")

print("OK" if not bad else f"Провалено: {bad}")
raise SystemExit(bool(bad))
